  left_join(oos, by = "model_set") %>% left_join(acc %>% filter(prediction == "leave-one-date-out"), by = "model_set") %>%
  left_join(ts %>% select(model_set, R2_temperature_by_season, departure_LRT_p), by = "model_set") %>%
  transmute(Model = lab_ms[model_set], `R² species only` = f2(`species only`, 3), `R² final` = f2(final, 3),
            `Predictive R², leave-one-date-out (species only)` = sprintf("%.2f (%.2f)", lodo_R2_final, lodo_R2_species),
            `Predictive R², leave-one-tree-out (species only)` = sprintf("%.2f (%.2f)", loto_R2_final, loto_R2_species),
