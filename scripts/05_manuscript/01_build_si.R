# ============================================================
# 01_build_si.R
# Builds the Supporting Information document entirely from pipeline outputs:
#   outputs/manuscript/Supporting_Information.docx
#   outputs/manuscript/si_items.csv   (item number, title, source file) for cross-referencing
# Every table is formatted from a CSV written by the analysis scripts and every figure is a
# file written by them; nothing is typed by hand except captions and the decay-class key.
# Run after the full pipeline (scripts/run_pipeline.sh calls it last).
# ============================================================
suppressPackageStartupMessages({ library(officer); library(flextable); library(dplyr); library(tidyr) })
OUT <- "outputs/manuscript"; dir.create(OUT, showWarnings = FALSE, recursive = TRUE)
T_ <- "outputs/tables"; MC <- file.path(T_, "model_checks"); MN <- file.path(T_, "manuscript"); FIG <- "outputs/figures"
rd <- function(f) read.csv(f, check.names = FALSE, stringsAsFactors = FALSE)
f2 <- function(x, d = 2) formatC(x, format = "f", digits = d)
fp <- function(p) ifelse(is.na(p), "", ifelse(p < 0.001, "<0.001", formatC(p, format = "f", digits = 3)))
star <- function(p) ifelse(is.na(p), "", ifelse(p < 0.001, "***", ifelse(p < 0.01, "**", ifelse(p < 0.05, "*", ""))))
sp_full <- c(bg = "N. sylvatica", rm = "A. rubrum", hem = "T. canadensis", ro = "Q. rubra")
term_lab <- function(t) { t <- gsub("TS_Ha[12]_raw_(\\d+)h", "Temperature (\\1 h)", t); t <- gsub("bvs_wtd_cm_raw_(\\d+)h", "Water table (\\1 h)", t)
  t <- gsub("NEON_SWC_shallow_raw_(\\d+)h", "Soil water (\\1 h)", t); t <- gsub("species", "", t); t <- gsub(":", " × ", t); t }

doc <- read_docx()
items <- list(); tab_n <- 0; fig_n <- 0
ft_style <- function(ft) ft %>% theme_booktabs() %>% fontsize(size = 8, part = "all") %>% font(fontname = "Arial", part = "all") %>%
  autofit() %>% fit_to_width(6.5)
add_table <- function(df, title, note, src) {
  tab_n <<- tab_n + 1
  doc <<- doc %>% body_add_par(sprintf("Table S%d. %s", tab_n, title), style = "Normal") %>%
    body_add_flextable(ft_style(flextable(df))) %>% body_add_par(note, style = "Normal") %>% body_add_par("", style = "Normal")
  items[[length(items) + 1]] <<- data.frame(item = sprintf("Table S%d", tab_n), title = title, source = src)
}
add_figure <- function(path, title, caption, w = 6.5, h = NULL) {
  if (!file.exists(path)) { warning("missing figure: ", path); return(invisible()) }
  fig_n <<- fig_n + 1
  if (is.null(h)) { dims <- dim(png::readPNG(path, native = TRUE)); h <- w * dims[1] / dims[2] }
  if (h > 8.5) { w <- w * 8.5 / h; h <- 8.5 }
  doc <<- doc %>% body_add_img(path, width = w, height = h) %>%
    body_add_par(sprintf("Figure S%d. %s %s", fig_n, title, caption), style = "Normal") %>% body_add_break()
  items[[length(items) + 1]] <<- data.frame(item = sprintf("Figure S%d", fig_n), title = title, source = path)
}

doc <- doc %>% body_add_par("Supporting Information", style = "heading 1") %>%
  body_add_par("Contrasting controls on tree methane emissions in upland and wetland forests", style = "Normal") %>%
  body_add_par(sprintf("Generated by scripts/05_manuscript/01_build_si.R on %s from the pipeline outputs.", Sys.Date()), style = "Normal") %>%
  body_add_break()

